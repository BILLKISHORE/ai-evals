def generate_html(storage):
    stats = storage.get_stats()
    runs = list(reversed(storage.list_runs(limit=500)))

    template = Template(HTML_TEMPLATE)
    return template.render(
        generated=datetime.now().isoformat(),
        stats=stats,
        runs=runs,
        mlcommons_mapping=HARM_TO_MLCOMMONS,
        mlcommons_hazards=MLCOMMONS_HAZARDS,
        version=__import__("mordor").__version__,
    )


def generate_markdown(storage):
    stats = storage.get_stats()
    runs = storage.list_runs(limit=500)

    lines = [
        "# AI Blackteam -- Security Report",
        f"\nGenerated: {datetime.now().isoformat()}",
        f"\n## Summary",
        f"- Total runs: {stats['total_runs']}",
        f"- Bypassed: {stats['bypassed']}",
        f"- Blocked: {stats['blocked']}",
        f"- Models tested: {stats['models_tested']}",
        f"- Attacks used: {stats['attacks_used']}",
        "",
        "## Results",
        "",
        "| # | Model | Attack | Verdict | Confidence |",
        "|---|-------|--------|---------|------------|",
    ]

    for run in reversed(runs):
        lines.append(
            f"| {run['id']} | {run['model']} | {run['attack']} | "
            f"{run['verdict']} | {run['confidence']:.2f} |"
        )

    lines.extend([
        "",
        "## MLCommons AILuminate Alignment",
        "",
        "| Harm Category | MLCommons Code | MLCommons Hazard |",
        "|---------------|----------------|------------------|",
    ])
    for harm, code in HARM_TO_MLCOMMONS.items():
        lines.append(f"| {harm} | {code} | {MLCOMMONS_HAZARDS[code]['name']} |")

    return "\n".join(lines) + "\n"


def generate_json(storage):
    runs = storage.list_runs(limit=500)
    stats = storage.get_stats()
    mlcommons_alignment = {
        harm: {"code": code, "name": MLCOMMONS_HAZARDS[code]["name"]}
        for harm, code in HARM_TO_MLCOMMONS.items()
    }
    return json.dumps(
        {"stats": stats, "runs": runs, "mlcommons_alignment": mlcommons_alignment},
        indent=2, default=str,
    )
