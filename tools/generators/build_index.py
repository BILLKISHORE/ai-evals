"""Parse all experiment frontmatter and generate INDEX.md."""

from collections import defaultdict
from datetime import date
from pathlib import Path

import yaml


def parse_frontmatter(filepath: Path) -> dict | None:
    """Extract YAML frontmatter from a markdown file."""
    content = filepath.read_text()
    if not content.startswith("---"):
        return None
    parts = content.split("---", 2)
    if len(parts) < 3:
        return None
    try:
        return yaml.safe_load(parts[1])
    except yaml.YAMLError:
        return None


def build_index(root_dir: Path) -> int:
    """Scan all experiments, parse frontmatter, write INDEX.md.

    Returns the number of experiments found.
    """
    experiments_dir = root_dir / "experiments"
    index_file = root_dir / "INDEX.md"

    experiments = []

    if experiments_dir.exists():
        for exp_dir in sorted(experiments_dir.iterdir()):
            if not exp_dir.is_dir() or exp_dir.name.startswith("."):
                continue
            readme = exp_dir / "README.md"
            if not readme.exists():
                continue
            meta = parse_frontmatter(readme)
            if meta and "id" in meta:
                meta["_dir"] = exp_dir.name
                experiments.append(meta)

    # Sort by ID
    experiments.sort(key=lambda e: e.get("id", ""))

    # Group by technique and model
    by_technique = defaultdict(list)
    by_model = defaultdict(list)
    severities = {"critical": 0, "high": 0, "medium": 0, "low": 0}

    for exp in experiments:
        exp_id = exp.get("id", "?")
        for tech in exp.get("techniques", []):
            by_technique[tech].append(exp_id)
        for model in exp.get("models", []):
            by_model[model].append(exp_id)
        sev = exp.get("severity", "low")
        if sev in severities:
            severities[sev] += 1

    # Count stats
    total = len(experiments)
    models_tested = len(by_model)
    techniques_used = len(by_technique)
    bounties = sum(1 for e in experiments if e.get("bug_bounty"))

    # Build markdown
    lines = [
        "# AI Blackteam -- Experiment Index",
        "",
        f"Last updated: {date.today().isoformat()}",
        "",
        "> Auto-generated by `python tools/cli.py index`",
        "",
    ]

    if not experiments:
        lines.extend([
            "## Experiments",
            "",
            "No experiments yet. Create your first one:",
            "",
            "```bash",
            'python tools/cli.py new --name "my-first-experiment" --technique prompt-injection --model gpt-5.4',
            "```",
        ])
    else:
        # All experiments table
        lines.extend([
            "## All Experiments",
            "",
            "| ID | Title | Model(s) | Technique(s) | Severity | Status |",
            "|----|-------|----------|-------------|----------|--------|",
        ])
        for exp in experiments:
            exp_id = exp.get("id", "?")
            title = exp.get("title", "Untitled")
            models = ", ".join(exp.get("models", []))
            techs = ", ".join(exp.get("techniques", []))
            severity = exp.get("severity", "?")
            status = exp.get("status", "?")
            dir_name = exp.get("_dir", "")
            lines.append(
                f"| [{exp_id}](experiments/{dir_name}/) | {title} | {models} | {techs} | {severity} | {status} |"
            )

        # By technique
        lines.extend(["", "## By Technique", ""])
        for tech, ids in sorted(by_technique.items()):
            lines.append(f"- **{tech}**: {', '.join(ids)}")

        # By model
        lines.extend(["", "## By Model", ""])
        for model, ids in sorted(by_model.items()):
            lines.append(f"- **{model}**: {', '.join(ids)}")

    # Stats
    lines.extend([
        "",
        "## Stats",
        f"- Total experiments: {total}",
        f"- Models tested: {models_tested}",
        f"- Techniques used: {techniques_used}",
        f"- Bug bounties submitted: {bounties}",
    ])

    index_file.write_text("\n".join(lines) + "\n")
    return total
